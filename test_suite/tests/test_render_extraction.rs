#[test]
fn test_render_extractor_basics() {
    let mut extractor = RenderExtractor::new();
    
    // Manually test path tracking
    extractor.push_path("field".to_string());
    assert_eq!(extractor.current_path(), "field");
    
    extractor.push_path("width".to_string());
    assert_eq!(extractor.current_path(), "field.width");
    
    extractor.pop_path();
    assert_eq!(extractor.current_path(), "field");
    
    extractor.pop_path();
    assert_eq!(extractor.current_path(), "");
}

#[test]
fn test_manual_extraction_approach() {
    let game = SoccerGame {
        field: Field {
            width: 100.0,
            height: 60.0,
        },
        ball: Ball {
            position: Vec2 { x: 50.0, y: 30.0 },
            velocity: Vec2 { x: 1.0, y: 0.5 },
            radius: 2.0,
        },
        players: vec![
            Player {
                position: Vec2 { x: 20.0, y: 30.0 },
                team: Team::Red,
                is_selected: false,
            },
            Player {
                position: Vec2 { x: 80.0, y: 30.0 },
                team: Team::Blue,
                is_selected: true,
            },
        ],
        score: [0, 0],
    };

    let wrapper = ExtractWrapper::new(game);
    let extracted = wrapper.extract_renderables();

    // Verify we extracted the right primitives
    assert!(extracted.contains_key("field"));
    assert!(extracted.contains_key("ball"));
    assert!(extracted.contains_key("players[0]"));
    assert!(extracted.contains_key("players[1]"));

    // Check ball primitive
    if let Some(Primitive::Circle { position, radius, color }) = extracted.get("ball") {
        assert_eq!(position.x, 50.0);
        assert_eq!(position.y, 30.0);
        assert_eq!(*radius, 2.0);
        assert_eq!(*color, Color::White);
    } else {
        panic!("Ball primitive not found or wrong type");
    }

    // Check player primitives
    if let Some(Primitive::Sprite { position, team_color, .. }) = extracted.get("players[0]") {
        assert_eq!(position.x, 20.0);
        assert_eq!(*team_color, Color::Red);
    } else {
        panic!("Player 0 primitive not found or wrong type");
    }
}

