/// Manual extraction approach - wraps a type and provides extraction
pub struct ExtractWrapper<T> {
    value: T,
    extractor: RenderExtractor,
}

impl<T> ExtractWrapper<T> {
    pub fn new(value: T) -> Self {
        Self {
            value,
            extractor: RenderExtractor::new(),
        }
    }

    pub fn extracted(&self) -> &HashMap<String, Primitive> {
        &self.extractor.extracted
    }
}

// We could implement custom extraction for specific types
impl ExtractWrapper<SoccerGame> {
    pub fn extract_renderables(mut self) -> HashMap<String, Primitive> {
        // Manually extract each renderable type
        self.extractor.path.push("field".to_string());
        self.extractor.emit(self.value.field.to_primitive());
        self.extractor.path.pop();

        self.extractor.path.push("ball".to_string());
        self.extractor.emit(self.value.ball.to_primitive());
        self.extractor.path.pop();

        for (i, player) in self.value.players.iter().enumerate() {
            self.extractor.path.push(format!("players[{}]", i));
            self.extractor.emit(player.to_primitive());
            self.extractor.path.pop();
        }

        self.extractor.extracted
    }
}

