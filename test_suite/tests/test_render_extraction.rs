pub struct MapSerializer<'a> {
    extractor: &'a mut RenderExtractor,
    key: Option<String>,
}

impl<'a> serde::ser::SerializeMap for MapSerializer<'a> {
    type Ok = ();
    type Error = ExtractorError;

    fn serialize_key<T: ?Sized>(&mut self, _key: &T) -> Result<(), ExtractorError>
    where
        T: Serialize,
    {
        // For simplicity, we don't format the key - just use a placeholder
        // In a real implementation, you'd serialize the key to a string
        self.key = Some("key".to_string());
        Ok(())
    }

    fn serialize_value<T: ?Sized>(&mut self, value: &T) -> Result<(), ExtractorError>
    where
        T: Serialize,
    {
        if let Some(key) = self.key.take() {
            self.extractor.push_path(key);
            value.serialize(&mut *self.extractor)?;
            self.extractor.pop_path();
        }
        Ok(())
    }

    fn end(self) -> Result<(), ExtractorError> {
        Ok(())
    }
}

