pub struct SeqSerializer<'a> {
    extractor: &'a mut RenderExtractor,
    index: usize,
}

impl<'a> serde::ser::SerializeSeq for SeqSerializer<'a> {
    type Ok = ();
    type Error = ExtractorError;

    fn serialize_element<T: ?Sized>(&mut self, value: &T) -> Result<(), ExtractorError>
    where
        T: Serialize,
    {
        self.extractor.push_path(format!("[{}]", self.index));
        value.serialize(&mut *self.extractor)?;
        self.extractor.pop_path();
        self.index += 1;
        Ok(())
    }

    fn end(self) -> Result<(), ExtractorError> {
        Ok(())
    }
}

