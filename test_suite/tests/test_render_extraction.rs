/// Custom serializer that extracts Renderable types while tracking paths
pub struct RenderExtractor {
    path: Vec<String>,
    extracted: HashMap<String, Primitive>,
}

impl RenderExtractor {
    pub fn new() -> Self {
        Self {
            path: Vec::new(),
            extracted: HashMap::new(),
        }
    }

    pub fn extract<T: Serialize>(value: &T) -> HashMap<String, Primitive> {
        let mut extractor = RenderExtractor::new();
        // We ignore the result since we're just walking the tree
        let _ = value.serialize(&mut extractor);
        extractor.extracted
    }

    fn current_path(&self) -> String {
        self.path.join(".")
    }

    fn push_path(&mut self, segment: String) {
        self.path.push(segment);
    }

    fn pop_path(&mut self) {
        self.path.pop();
    }

    // Helper to emit a primitive if we detect a Renderable type
    // This is called manually in test code since we can't do runtime type detection
    pub fn emit(&mut self, primitive: Primitive) {
        let path = self.current_path();
        self.extracted.insert(path, primitive);
    }
}

