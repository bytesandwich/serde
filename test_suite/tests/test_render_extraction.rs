#[derive(Debug, Clone, Copy, PartialEq, DeriveSerialize)]
pub enum Team {
    Red,
    Blue,
}

#[derive(DeriveSerialize, Clone)]
pub struct Ball {
    pub position: Vec2,
    pub velocity: Vec2,
    pub radius: f32,
}

impl Renderable for Ball {
    fn to_primitive(&self) -> Primitive {
        Primitive::Circle {
            position: self.position.clone(),
            radius: self.radius,
            color: Color::White,
        }
    }
}

#[derive(DeriveSerialize, Clone)]
pub struct Player {
    pub position: Vec2,
    pub team: Team,
    pub is_selected: bool,
}

impl Renderable for Player {
    fn to_primitive(&self) -> Primitive {
        let team_color = match self.team {
            Team::Red => Color::Red,
            Team::Blue => Color::Blue,
        };
        Primitive::Sprite {
            position: self.position.clone(),
            sprite_id: "player".to_string(),
            team_color,
        }
    }
}

#[derive(DeriveSerialize, Clone)]
pub struct Field {
    pub width: f32,
    pub height: f32,
}

impl Renderable for Field {
    fn to_primitive(&self) -> Primitive {
        Primitive::Rectangle {
            position: Vec2 { x: 0.0, y: 0.0 },
            width: self.width,
            height: self.height,
            color: Color::White,
        }
    }
}

#[derive(DeriveSerialize)]
pub struct SoccerGame {
    pub field: Field,
    pub ball: Ball,
    pub players: Vec<Player>,
    pub score: [u32; 2],
}

// Manual implementation of Extractable for SoccerGame
// (In real code, this would be generated by #[derive(Extractable)])
impl Extractable for SoccerGame {
    fn extract_renderables(&self) -> HashMap<String, Primitive> {
        let mut result = HashMap::new();
        
        // Extract field
        ExtractHelper::extract(&self.field, "field", "", &mut result);
        
        // Extract ball
        ExtractHelper::extract(&self.ball, "ball", "", &mut result);
        
        // Extract players (Vec implementation handles indices)
        ExtractHelper::extract(&self.players, "players", "", &mut result);
        
        result
    }
}

